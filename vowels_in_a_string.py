string1 = input().lower()
vowels = ""

if "a" in string1:
    vowels = vowels + "a"
if "e" in string1:
    vowels = vowels + "e"
if "i" in string1:
    vowels = vowels + "i"
if "o" in string1:
    vowels = vowels + "o"
if "u" in string1:
    vowels = vowels + "u"

print(vowels)                 